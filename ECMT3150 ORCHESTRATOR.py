def discover_rscript() -> Optional[str]:
    """Find Rscript on PATH or common Windows installation paths."""
    on_path = shutil.which("Rscript")
    if on_path:
        return on_path

    patterns = [
        r"C:\Program Files\R\R-*\bin\Rscript.exe",
        r"C:\Program Files (x86)\R\R-*\bin\Rscript.exe",
        str(Path.home() / "AppData/Local/Programs/R/R-*/bin/Rscript.exe"),
        r"C:\R\R-*\bin\Rscript.exe",
        r"C:\Program Files\R\*\bin\Rscript.exe",
        r"C:\Program Files (x86)\R\*\bin\Rscript.exe",
    ]
    found = []
    for pattern in patterns:
        found.extend(glob.glob(pattern))
    if not found:
        return None
    # Lexicographic sorting is adequate for discovery, but the user can set
    # RSCRIPT_EXE below to pin a specific R installation.
    return sorted(found, reverse=True)[0]


